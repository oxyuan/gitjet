// tr returns the message in l.
func (l lang) tr(key string) string {
	if m, ok := messages[l][key]; ok {
		return m
	}
	if l == langZH {
		if m, ok := uiZH[key]; ok {
			return m
		}
	}
	if m, ok := messages[langEN][key]; ok {
		return m
	}
	return key
}

